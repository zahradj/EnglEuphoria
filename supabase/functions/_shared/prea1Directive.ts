export function buildPreA1Directive(hub: HubId): string {
  return [
    `=== PRE-A1 MASTER DIRECTIVE (tier 3, HARD — overrides style/gamification/UI, never CEFR/curriculum/age safety) ===`,
    ``,
    `5 ARCHITECTURAL PILLARS (immutable, all hubs):`,
    `1. Receptive-First Input — first 2 activities of every Pre-A1 lesson MUST be non-verbal (point/match/drag/listen-and-do). Forced speaking = HARD reject.`,
    `2. Formulaic Lexical Chunking — NEVER teach isolated words at Pre-A1. Every target word ships inside a high-utility chunk.`,
    `3. Visual Scaffolding — default UI for sentence/grammar is a substitution table: emit substitution_table: { columns: string[][] }.`,
    `4. Systematic Synthetic Phonics — pure sounds, not letter names; Jolly Group 1→7 progression; TPR + tracing before reading. Standalone phonics = Playground only.`,
    `5. Spaced Retrieval + Affective Adaptation — review intervals 1/2/4/8 days. Anxiety triggers (trace>9px, vol<-40dB, silence>3s) → swap to a low-pressure game. No public correction.`,
    ``,
    `OUTPUT CONTRACT:`,
    `- Lexical chunks emit chunk: "..." per vocab item.`,
    `- Phonics activities emit { phoneme, grapheme, tpr_action, trace_strokes }.`,
    `- Substitution tables emit substitution_table: { columns: string[][] }.`,
    `- CEFR caps (Pre-A1): max 5 words/sentence, 1 clause, ≤2 syllables/word, no abstract concepts.`,
    `- Banned grammar at Pre-A1: passive, perfect tenses, conditionals, subjunctive, inversion, reported-speech backshift, modal perfects, relative clauses.`,
    ``,
    HUB_BLOCK[hub],
    LESSON_DESIGN_ENGINE,
    CHIEF_DESIGNER,
    ACTIVITY_BRAIN,
    LESSON_1_SPEC,
    `=== END PRE-A1 MASTER DIRECTIVE ===`,
  ].join("\n");
}
