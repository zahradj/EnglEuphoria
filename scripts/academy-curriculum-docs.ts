// Generates docs/academy-curriculum/<level>.md (one curriculum per level) and an index, from the roadmap data + level frames.
// Run: npx tsx scripts/academy-curriculum-docs.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { ACADEMY_ROADMAP, PA1_SEASONS } from '../src/curriculum/academy';
import { LEVEL_FRAMES } from '../src/curriculum/academy/levelFrames';

const DIR = 'docs/academy-curriculum';
mkdirSync(DIR, { recursive: true });
const list = (a: readonly string[]) => a.map((x) => `- ${x}`).join('\n');
const index: string[] = ['# Academy curriculum — one document per level (generated)', '', '> Generated by `scripts/academy-curriculum-docs.ts` from `src/curriculum/academy/` (Seasons, structures) and `levelFrames.ts` (level design). Edit the data, not these files. Age band 13–18. One-to-one, 60-minute live lessons, 8 per Season.', '', '| Level | Seasons | Lessons | Document |', '|---|---|---|---|'];
let cumSessions = 0;

for (const f of LEVEL_FRAMES) {
  const plan = ACADEMY_ROADMAP.find((p) => p.level === f.level);
  const seasons = plan?.seasons ?? [];
  const n = f.level === 'Pre-A1' ? PA1_SEASONS.length : seasons.length;
  const sessions = n * 8;
  cumSessions += sessions;
  const o: string[] = [];
  const out = (s = '') => o.push(s);
  out(`# Academy curriculum — ${f.level}`);
  out();
  out(`> Generated. ${n} Seasons × 8 = **${sessions} live lessons** of 60 minutes (cumulative live hours from Pre-A1: **${cumSessions}**). Plan rule: every lesson has an approved one-to-one plan first (\`docs/academy-lesson-plan-template.md\`) with research logged in \`docs/research/\`.`);
  out();
  out('## 1. Level at a glance');
  out(`- **CEFR:** ${f.cefrNote}`);
  out(`- **The student:** ${f.student}`);
  out(`- **Method:** ${f.method}`);
  out(`- **Supports:** ${f.supports}`);
  out(`- **Input texts:** ${f.inputText}`);
  out(`- **Daily 10:** ${f.daily10}`);
  out();
  out('## 2. Skills balance (design targets for live practice time)');
  out('| Skill | Share |'); out('|---|---|');
  Object.entries(f.skills).forEach(([k, v]) => out(`| ${k} | ${v} % |`));
  out();
  out('## 3. Season sequence');
  if (f.level === 'Pre-A1') {
    out('| Season | Title · theme | Chunk | Sounds | New items | Release |'); out('|---|---|---|---|---|---|');
    PA1_SEASONS.forEach((s) => out(`| ${s.id} | **${s.title}** · ${s.theme} | ${s.chunk} | ${s.sounds.join(' ') || 'review'} | ${s.episodes.reduce((a, e) => a + e.newItems.length, 0)} | ${s.release} |`));
    out();
    out('Seasons P4–P6 (the Full ladder) are proposals only: `docs/academy-pre-a1-curriculum.md`.');
  } else {
    out('| Season | Title · theme | Structures | Functions | New items | Release |'); out('|---|---|---|---|---|---|');
    seasons.forEach((s) => out(`| ${s.id}${s.bigRemix ? ' · Remix' : ''}${s.levelCheck ? ' · **level check**' : ''} | **${s.title}** · ${s.theme} | ${s.structures.map((x) => x.label).join('; ')} | ${s.functions.join('; ')} | ${s.newItemBudget} | ${s.release} |`));
    out();
    out(`Total new items at this level (budget): **${seasons.reduce((a, s) => a + s.newItemBudget, 0)}**; cumulative target ${plan?.cumulativeItemTarget}.`);
  }
  out();
  out('## 4. Every Season has the same eight lessons');
  out('Cold Open (hook, gist) · Word Lab (vocabulary and pronunciation) · Pattern Lab (grammar noticing) · On Air (real exchange) · Deep Dive (longer text and short writing) · Side Quest (student\'s pick, light new language) · Remix (zero new language) · Finale (peer task, Release, checkpoint, zero new language). Run of show: standard 60 minutes (Pre-A1 uses its own slower one).');
  out();
  out('## 5. Pronunciation and L1 priorities');
  out(list(f.l1Priorities));
  if (seasons.length) { out(); out('Season pronunciation focus:'); seasons.forEach((s) => out(`- ${s.id}: ${s.pronunciation.join('; ')}`)); }
  out();
  out('## 6. Assessment');
  out(list(f.assessment));
  out();
  out('## 7. To move up to the next level');
  out(list(f.moveUp));
  out();
  out('## 8. Lanes (school and exam practice, inside the Season; see `docs/academy-curriculum-gaps-plan.md`)');
  out(f.lanes);
  out();
  out('## 9. Games and video-game mechanics');
  out(`- **Game mix:** ${f.gamesMix}`);
  out(`- **Video-game mechanics for this level:**\n${list(f.videoGameMechanics)}`);
  out('- Lists: `docs/academy-games-catalog.md` (168), `docs/academy-video-game-mechanics.md`.');
  out();
  out('## 10. Teen topics');
  out(list(f.teenTopics));
  if (seasons.length) {
    out();
    out('## 11. Season details');
    seasons.forEach((s) => {
      out(`### ${s.id} ${s.title}`);
      out(`*${s.hook}*`);
      out(list(s.canDo));
      out(`- Lexical fields: ${s.lexicalFields.join('; ')}`);
      if (s.mediation) out(`- Mediation: ${s.mediation}`);
      out(`- Skins: ${s.skins.map((k) => k.id).join(', ')}`);
      out();
    });
  }
  out('---');
  out('Status: can-do lines are paraphrases (not verified against the Companion Volume); "[target]" numbers are design goals; items to review: `docs/research/academy-curriculum-primary-source-check.md`.');
  const file = `${f.level.toLowerCase()}.md`;
  writeFileSync(`${DIR}/${file}`, o.join('\n') + '\n');
  index.push(`| ${f.level} | ${n} | ${sessions} | [${file}](./${file}) |`);
}
index.push('', `Total: ${cumSessions} live lessons.`);
writeFileSync(`${DIR}/README.md`, index.join('\n') + '\n');
console.log('wrote', LEVEL_FRAMES.length, 'level documents');
