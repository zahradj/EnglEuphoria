// Generates docs/research/academy-gse-grammar-check-a2-c1.md from src/curriculum/academy/gse/ (run: npx tsx scripts/academy-gse-report.ts).
import { writeFileSync } from 'node:fs';
import { ACADEMY_SEASONS } from '../src/curriculum/academy';
import { STRUCTURE_GSE } from '../src/curriculum/academy/gse';
import { GSE_BAND_TOP } from '../src/curriculum/academy/structureGse';

const BAND: Record<string, [number, number]> = { A2: [30, 42], B1: [43, 58], B2: [59, 75], C1: [76, 84] };
const rows: string[] = [];
const flags: Record<string, string[]> = { A2: [], B1: [], B2: [], C1: [] };
for (const level of ['A2', 'B1', 'B2', 'C1'] as const) {
  rows.push(`\n## ${level} (GSE band ${BAND[level][0]}-${BAND[level][1]}; introduce up to about ${GSE_BAND_TOP[level] + 10})\n`, '| Season | Structure | GSE | Reading | From |', '|---|---|---|---|---|');
  for (const s of ACADEMY_SEASONS.filter((x) => x.level === level)) for (const x of s.structures) {
    const e = STRUCTURE_GSE[x.id];
    if (!e) continue;
    let reading = 'in band';
    if (!e.gse) reading = 'no objective in the list';
    else if (e.gse[0] > GSE_BAND_TOP[level] + 10) reading = '**above the 10-point lead**';
    else if (e.gse[1] > GSE_BAND_TOP[level]) reading = 'above the band, within the lead' + (e.chunkFirst ? ' (chunk first)' : '');
    else if (e.gse[1] < BAND[level][0]) reading = '**rated a LOWER level**';
    else if (e.gse[0] < BAND[level][0]) reading = 'partly lower';
    if (/above the 10|LOWER/.test(reading)) flags[level].push(`${s.id} ${x.id} (${e.gse ? e.gse.join('-') : 'none'})`);
    rows.push(`| ${s.id} | ${x.id} | ${e.gse ? (e.gse[0] === e.gse[1] ? e.gse[0] : e.gse.join('-')) : 'none'} | ${reading} | ${e.from.replace(/\|/g, '/')} |`);
  }
}
const out = [
  '# A2-C1 roadmap — structures against the Pearson GSE adult grammar objectives (generated 2026-10-17)',
  '',
  '> Generated by `scripts/academy-gse-report.ts` from `src/curriculum/academy/gse/` (data) and the roadmap. Edit the data, not this file.',
  '> Source: Pearson, *GSE Learning Objectives: Grammar, Adult Learners* (Feb 2023), read from the PDF text; method and limits in `docs/research/academy-a1-gse-grammar-check.md`. The numbers were mapped by four agents from the rows they read, then spot-read by me; **mapping a structure to its objectives involves judgement** (sub-uses, wording), so treat single numbers as indicative and verify before moving a Season.',
  '> The GSE value is the point of 50 % success; Pearson says to introduce a structure about 10 points before it. A structure is flagged only when its LOWEST sub-use is above band top + 10, or when the whole structure is rated a lower level than ours.',
  '',
  '## Flags (candidates for a roadmap decision, none applied)',
  ...(['A2', 'B1', 'B2', 'C1'] as const).flatMap((l) => [`- **${l}:** ${flags[l].length ? flags[l].join('; ') : 'none'}`]),
  ...rows,
];
writeFileSync('docs/research/academy-gse-grammar-check-a2-c1.md', out.join('\n') + '\n');
console.log('flags', JSON.stringify(flags, null, 1));
