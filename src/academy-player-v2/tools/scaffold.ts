// Lesson scaffold (adapted from the Playground's lesson process, re-implemented for the Academy): from a blueprint id it produces the files a new lesson needs,
// every one of them INVALID until a person (or the lesson-creation protocol) fills it in, so nothing half-made can ship.
//   npx tsx scripts/academy-new-lesson.mjs B1-S01-E4            writes the files and prints the checklist
//   npx tsx scripts/academy-new-lesson.mjs B1-S01-E4 --dry      only prints
import type { AcademyLessonBlueprint } from '../../curriculum/academy';

export interface ScaffoldFile { path: string; content: string }
export interface Scaffold { files: ScaffoldFile[]; registration: string; checklist: string[] }

const fileSlug = (id: string) => id.toLowerCase().replace(/-/g, '');
const constName = (id: string) => id.replace(/-/g, '_');

export function scaffoldLesson(bp: AcademyLessonBlueprint): Scaffold {
  const id = bp.id;
  const slug = fileSlug(id);
  const [lvl, season, ep] = id.toLowerCase().split('-');
  // no fixed skeleton (docs/academy-lesson-design.md): the author names the acts; this starts with three placeholders summing to 60
  const parts = [{ name: 'TODO act 1: the lesson\'s own name for it', minutes: 15, mustHave: [] as string[] }, { name: 'TODO act 2', minutes: 30, mustHave: [] as string[] }, { name: 'TODO act 3', minutes: 15, mustHave: [] as string[] }];
  const minutes = parts.map((p) => p.minutes);
  const cast = [...new Set([bp.cast?.lead, ...(bp.cast?.appears ?? []).map((a) => a.name)].filter(Boolean))] as string[];
  const partComments = parts.map((p, i) => `  // ---------- ${i} · ${p.name} (${p.minutes} min) ----------\n${(p.mustHave ?? []).map((m) => `  //   must have: ${m}`).join('\n')}\n  // TODO scenes for part ${i}`).join('\n');

  const script = `// ${id} "${bp.title}" — SCAFFOLD (generated by scripts/academy-new-lesson.mjs). Not registered, not valid: finish it, then register it in lessonScripts.ts.
// Blueprint: ACADEMY_LESSON_BLUEPRINTS '${id}' (objective, Mission, Release, clue; no fixed run of show: analyse, research, choose the approach, then author your own acts, docs/academy-lesson-design.md). Plan: docs/academy-${lvl}-${season}-${ep}-plan.md (the owner approves it BEFORE this file is built).
// Research: docs/research/academy-${lvl}-${season}-${ep}-research.md (a "Game search" section with 1-2 chosen games per success criterion).
// Rules to satisfy (CLAUDE.md): model then rule BEFORE the production games; speaking in at least 4 parts; every scene on a reviewed illustrated plate; art reviewed in artReview.ts; >= 80 student responses; several different games, each tied to a criterion.
import type { LessonScript, SceneBase } from '../types';
import type { LobbyScene } from '../scenes/lobby/Lobby';
import type { WrapScene } from '../scenes/wrap/Wrap';

export const CRITERIA: string[] = [
  // TODO: 3-5 observable "I can ..." lines (the teacher marks them). Objective: ${JSON.stringify(bp.objective)}
];

// the scenes carry the fields of their kind, checked by \`satisfies\` and the registry validator
type Scene = SceneBase & Record<string, unknown>;
const PLATE = 'TODO-reviewed-plate-id'; // public/academy-art/bg/<id>.webp, listed ok in artReview.ts
const scenes: Scene[] = [
  { id: 'lobby', part: 0, kind: 'lobby', plate: PLATE, heading: ${JSON.stringify(bp.title.split('·').pop()?.trim() ?? bp.title)}, sub: 'TODO' } satisfies LobbyScene,
${partComments}
  { id: 'wrap', part: ${parts.length - 1}, kind: 'wrap', plate: PLATE, heading: 'TODO', teachBack: 'TODO: the rule, restated by the student' } satisfies WrapScene,
];

export const ${constName(id)}: LessonScript = {
  blueprintId: '${id}',
  title: ${JSON.stringify(bp.title)},
  criteria: CRITERIA,
  cast: ${JSON.stringify(cast)} as LessonScript['cast'],
  partMinutes: ${JSON.stringify(minutes)},
  scenes,
};
export default ${constName(id)};
`;

  const research = `# Research — ${id} "${bp.title}" (stub, fill in)

Rule: CLAUDE.md "Research for every unit and every lesson" and "Every lesson researches compatible games". Mechanics only, never content. Mark every source VERIFIED (page opened) or UNVERIFIED (search snippet).

## 1. Sources (level, grammar, vocabulary, L1 difficulties)
| Source | What was taken | Quality / limits | Mark |
|---|---|---|---|
| TODO | | | |

## 2. Game search (per success criterion)
At least 5 candidates from at least 3 source families (A publishers/councils, B apps and teacher sites, C video games and game-design/learning research). One to two CHOSEN games per success criterion.
| # | Candidate | Family | Source (URL, VERIFIED/UNVERIFIED) | Mechanic | Alignment (criterion, English practised, comfort) | Verdict |
|---|---|---|---|---|---|---|
| 1 | TODO | | | | | |

| Criterion | Chosen game(s) | Scene kind | Video-game mechanic borrowed |
|---|---|---|---|
| 1 | TODO | | |

## 3. What this changes in the plan
TODO
`;

  const plan = `# ${id} "${bp.title}" — lesson plan (for owner approval, stub)

Status: **not approved. Nothing is built until the owner approves this plan** (CLAUDE.md "A lesson plan comes before every lesson"). Copy of docs/academy-lesson-plan-template.md with the blueprint facts filled in.

Blueprint: objective ${JSON.stringify(bp.objective)}; primary skill ${bp.primarySkill}; new items ${bp.newItems?.count} (${bp.newItems?.kind}); builds on ${(bp.buildsOn?.lessonIds ?? []).join(', ')}; Mission ${JSON.stringify(typeof bp.mission === 'string' ? bp.mission : bp.mission ?? '')}; Release ${JSON.stringify(typeof bp.release === 'string' ? bp.release : bp.release ?? '')}.

${'TODO: sections 1-10 of the template (student need, objective and exit task, research log, run of show with minutes and responses, speaking, gamified practice, games and video-game mechanic per criterion, traceability, supports, assessment, before building).'}
`;

  const files: ScaffoldFile[] = [
    { path: `src/academy-player-v2/lessons/${slug}.ts`, content: script },
    { path: `docs/research/academy-${lvl}-${season}-${ep}-research.md`, content: research },
    { path: `docs/academy-${lvl}-${season}-${ep}-plan.md`, content: plan },
  ];
  const registration = `  '${id}': () => import('./lessons/${slug}').then((m) => m.${constName(id)}),   // add to LOADERS in src/academy-player-v2/lessonScripts.ts`;
  const checklist = [
    '1. Write the lesson plan (docs/academy-' + lvl + '-' + season + '-' + ep + '-plan.md) and get the OWNER\'S written approval.',
    '2. Research on the internet and fill the "Game search" section (1-2 chosen games per criterion; mark sources verified or unverified).',
    '3. Pictures: reuse reviewed plates/cards, or make new ones in Canva one at a time with the owner; review each in src/academy-player-v2/artReview.ts (npx tsx scripts/academy-art-sheet.mjs ' + id + ' lists them).',
    '4. Fill in the lesson file; run `npm run typecheck:academy-player` and `npx vitest run src/academy-player-v2`.',
    '5. Register it in lessonScripts.ts and add its library card in src/academy-deck/lessonRegistry.ts (id = blueprint id; ACADEMY_DECK_BLUEPRINT_IDS).',
    '6. Voice: `npx tsx scripts/academy-voice-lines.mjs`, check `node scripts/bake-academy-voice.mjs --audit`, push (the workflow bakes the clips).',
    '7. Screenshots at 1280x720 and 390x844 (preview: /academy-player-v2-preview.html?lesson=' + id + '), the dullness test, then the academy-quality-gate report.',
  ];
  return { files, registration, checklist };
}
